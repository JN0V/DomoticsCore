void test_reconnect_success_emits_events(void) {
    buildStaFixture();
    const auto& st = HAL::WiFiImpl::stubWifiState();

    TEST_ASSERT_EQUAL_UINT(1, st.connectCalls);  // begin() started the attempt
    TEST_ASSERT_EQUAL_STRING("Net", st.lastConnectSSID.c_str());
    TEST_ASSERT_TRUE(wifiPtr->isConnectionInProgress());

    HAL::WiFiImpl::setConnectedForTest(true);
    HAL::Platform::advanceMillisForTest(101);  // past the 100 ms poll timer
    testCore->loop();

    TEST_ASSERT_FALSE(wifiPtr->isConnectionInProgress());
    TEST_ASSERT_EQUAL_INT((int)ComponentStatus::Success, (int)wifiPtr->getLastStatus());
    TEST_ASSERT_EQUAL_INT(1, (int)staEvents.size());
    TEST_ASSERT_TRUE(staEvents[0]);
    TEST_ASSERT_EQUAL_INT(1, (int)readyPayloads.size());
    TEST_ASSERT_EQUAL_STRING("0.0.0.0", readyPayloads[0].c_str());
}

void test_connection_timeout_then_same_tick_retry(void) {
    buildStaFixture();
    const auto& st = HAL::WiFiImpl::stubWifiState();

    HAL::Platform::advanceMillisForTest(15001);  // past CONNECTION_TIMEOUT
    testCore->loop();

    TEST_ASSERT_EQUAL_INT((int)ComponentStatus::TimeoutError, (int)wifiPtr->getLastStatus());
    TEST_ASSERT_EQUAL_INT(1, (int)staEvents.size());
    TEST_ASSERT_FALSE(staEvents[0]);
    // Deliberate behaviour pin: the retry fires in the SAME loop() as the
    // timeout — the 5 s reconnect timer is always ready when the 15 s timeout
    // fires. Reorder loop() and this red tells you the retry latency changed.
    TEST_ASSERT_EQUAL_UINT(2, st.connectCalls);
    TEST_ASSERT_TRUE(wifiPtr->isConnectionInProgress());
}

void test_disconnect_stops_reconnection(void) {
    buildStaFixture();
    const auto& st = HAL::WiFiImpl::stubWifiState();

    HAL::Platform::advanceMillisForTest(15001);
    testCore->loop();  // timeout + same-tick retry → 2 calls
    TEST_ASSERT_EQUAL_UINT(2, st.connectCalls);

    wifiPtr->disconnect();
    unsigned before = st.connectCalls;
    HAL::Platform::advanceMillisForTest(20000);  // second attempt times out too
    testCore->loop();

    TEST_ASSERT_EQUAL_UINT(before, st.connectCalls);
    TEST_ASSERT_FALSE(wifiPtr->isConnectionInProgress());
}

void test_low_heap_defers_connection_until_retry_tick(void) {
    // Standalone — no begin(), so the guard path owns every observable.
    WifiComponent wifi("Net", "pw");
    const auto& st = HAL::WiFiImpl::stubWifiState();

    HAL::Platform::setFreeHeapForTest(2000);  // below the 2500 connect guard
    wifi.setCredentials("Net2", "pw2", true);

    TEST_ASSERT_EQUAL_UINT(0, st.connectCalls);
    TEST_ASSERT_FALSE(wifi.isConnectionInProgress());

    // "Will retry on next reconnectTimer tick" (Wifi.h:948) — heap recovers,
    // 5 s pass, the deferred connect happens.
    HAL::Platform::resetFreeHeapForTest();
    HAL::Platform::advanceMillisForTest(5001);
    wifi.loop();

    TEST_ASSERT_EQUAL_UINT(1, st.connectCalls);
    TEST_ASSERT_EQUAL_STRING("Net2", st.lastConnectSSID.c_str());
    TEST_ASSERT_TRUE(wifi.isConnectionInProgress());
}

