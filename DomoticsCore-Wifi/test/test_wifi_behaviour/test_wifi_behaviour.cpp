void test_fallback_arms_at_low_heap_boot(void) {  // F1
    buildStaFixture();
    armFallbackAt3000();
    // AP torn down for the attempt → the UI heard about it.
    TEST_ASSERT_EQUAL_INT(1, (int)apEvents.size());
    TEST_ASSERT_FALSE(apEvents[0]);
}

void test_fallback_success_stays_sta_only_when_heap_low(void) {  // F2
    buildStaFixture();
    armFallbackAt3000();
    const auto& st = HAL::WiFiImpl::stubWifiState();

    HAL::WiFiImpl::setConnectedForTest(true);
    HAL::Platform::advanceMillisForTest(1);
    unsigned startBefore = st.startAPCalls;
    testCore->loop();

    // Heap 3000 ≤ 6500: the AP is NOT restarted — WebUI keeps its 4 KB.
    TEST_ASSERT_EQUAL_UINT(startBefore, st.startAPCalls);
    TEST_ASSERT_EQUAL_INT((int)Mode::Station, (int)HAL::WiFiHAL::getMode());
    TEST_ASSERT_EQUAL_INT((int)ComponentStatus::Success, (int)wifiPtr->getLastStatus());
    TEST_ASSERT_EQUAL_INT(1, (int)staEvents.size());
    TEST_ASSERT_TRUE(staEvents[0]);
}

void test_fallback_success_restarts_ap_when_heap_allows(void) {  // F3
    buildStaFixture();
    armFallbackAt3000();  // phase 1 — heap 20000 here would never arm (review finding 1)
    const auto& st = HAL::WiFiImpl::stubWifiState();

    HAL::Platform::setFreeHeapForTest(20000);  // > 6500: AP+STA affordable now
    HAL::WiFiImpl::setStartAPResultForTest(true);
    HAL::WiFiImpl::setConnectedForTest(true);
    HAL::Platform::advanceMillisForTest(1);
    unsigned startBefore = st.startAPCalls;
    testCore->loop();

    TEST_ASSERT_EQUAL_UINT(startBefore + 1, st.startAPCalls);
    TEST_ASSERT_EQUAL_STRING("FallAP", st.apSSID.c_str());
    TEST_ASSERT_EQUAL_INT((int)Mode::StationAndAP, (int)HAL::WiFiHAL::getMode());
    // Sequence: disabled by the arming teardown, re-enabled on STA's channel.
    TEST_ASSERT_EQUAL_INT(2, (int)apEvents.size());
    TEST_ASSERT_FALSE(apEvents[0]);
    TEST_ASSERT_TRUE(apEvents[1]);
}

void test_fallback_timeout_restores_ap_and_saves_config(void) {  // F4
    buildStaFixture();
    wifiPtr->setConfigSaveCallback(captureConfigSave);
    armFallbackAt3000();
    const auto& st = HAL::WiFiImpl::stubWifiState();

    unsigned startBefore = st.startAPCalls;
    HAL::Platform::advanceMillisForTest(30001);  // past the 30 s fallback window
    testCore->loop();

    TEST_ASSERT_EQUAL_UINT(startBefore + 1, st.startAPCalls);
    TEST_ASSERT_EQUAL_STRING("FallAP", st.apSSID.c_str());
    TEST_ASSERT_EQUAL_INT((int)Mode::AccessPoint, (int)HAL::WiFiHAL::getMode());
    TEST_ASSERT_FALSE(wifiPtr->isWifiEnabled());
    // The anti-boot-loop save: autoConnect=false so the next boot does not
    // retry a dead STA forever, enableAP=true so the device stays reachable.
    TEST_ASSERT_TRUE(configSaved);
    TEST_ASSERT_FALSE(savedConfig.autoConnect);
    TEST_ASSERT_TRUE(savedConfig.enableAP);
    TEST_ASSERT_EQUAL_STRING("Net", savedConfig.ssid.c_str());
    // AP back up → the UI heard disabled (arming) then enabled (restore),
    // and network/ready re-announced the AP address.
    TEST_ASSERT_EQUAL_INT(2, (int)apEvents.size());
    TEST_ASSERT_TRUE(apEvents[1]);
    TEST_ASSERT_EQUAL_INT(1, (int)readyPayloads.size());
    TEST_ASSERT_EQUAL_STRING("0.0.0.0", readyPayloads[0].c_str());
}

void test_ap_client_low_heap_reboots_to_sta(void) {  // F5
    buildStaFixture();
    const auto& st = HAL::WiFiImpl::stubWifiState();

    WifiConfig cfg;
    cfg.ssid = "Net";
    cfg.password = "pw";
    cfg.autoConnect = true;
    cfg.enableAP = true;
    cfg.apSSID = "FallAP";
    cfg.apPassword = "appw";
    wifiPtr->setConfig(cfg);

    HAL::WiFiImpl::setAPStationCountForTest(1);  // a browser is on the AP
    HAL::Platform::setFreeHeapForTest(3000);
    unsigned stopBefore = st.stopAPCalls;
    testCore->loop();

    // Nothing is torn down while the client is connected — the reboot is the
    // whole mechanism (STA needs more heap than a live AP+HTTP can spare).
    TEST_ASSERT_EQUAL_UINT(stopBefore, st.stopAPCalls);
    TEST_ASSERT_EQUAL_UINT(0, HAL::Platform::restartCountForTest);

    HAL::Platform::advanceMillisForTest(1500);  // the deferred-reboot window
    testCore->loop();
    // Per-fire, not latched: a third loop after another 1500 ms would read 2.
    TEST_ASSERT_EQUAL_UINT(1, HAL::Platform::restartCountForTest);
}

void test_ultra_low_heap_guard_disables_sta(void) {  // F6
    // Standalone, no begin(): the guard path must own every observable
    // (review finding 3 — loop() discards updateWifiMode()'s return).
    WifiComponent wifi("Net", "pw");
    wifi.setConfigSaveCallback(captureConfigSave);
    const auto& st = HAL::WiFiImpl::stubWifiState();

    HAL::Platform::setFreeHeapForTest(1500);  // below the 2000 hard floor
    TEST_ASSERT_FALSE(wifi.enableWifi(true));

    TEST_ASSERT_FALSE(wifi.isWifiEnabled());
    TEST_ASSERT_TRUE(configSaved);
    TEST_ASSERT_FALSE(savedConfig.autoConnect);
    // ANY WiFi SDK call may crash at this heap — the guard's contract is that
    // it makes none.
    TEST_ASSERT_EQUAL_UINT(0, st.connectCalls);
    TEST_ASSERT_EQUAL_UINT(0, st.startAPCalls);
    TEST_ASSERT_EQUAL_UINT(0, st.stopAPCalls);
    TEST_ASSERT_EQUAL_UINT(0, st.disconnectCalls);
    TEST_ASSERT_EQUAL_UINT(0, st.disconnectAndOffCalls);
    TEST_ASSERT_EQUAL_INT((int)Mode::Off, (int)HAL::WiFiHAL::getMode());
}

