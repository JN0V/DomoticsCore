// TEST-4 — WiFi behavioural coverage: reconnection, STA fallback timer, AP mode.
//
// Until this suite, every one of these paths was unreachable natively: the
// clock was the wall clock (a timeout test would take 15 real seconds), the
// heap was frozen at 65536 (no low-heap branch could open), and the WiFi stub
// was stateless (mode always Off, startAP always false — the skip-restart
// branch compares both against what startAP was given). The seams this suite
// drives are Platform_Stub.h's scriptable millis/heap/restart-count and
// Wifi_Stub.h's mode/AP/connect record; every seam default is byte-identical
// to the old stubs.
//
// Contract: _bmad-output/implementation-artifacts/spec-test-4-wifi-behaviour-
// coverage.md (v2 — two tests were refuted as first specified; the fixture
// rules below come from that review).
//
// Fixture invariants:
// - The millis override is installed BEFORE the component is constructed:
//   NonBlockingDelay captures getMillis() at construction, and a timer
//   anchored to the wall clock then read against an override at 0 wraps and
//   fires once spuriously.
// - F-scenarios construct with STA credentials. A default-constructed
//   component's begin() starts the autogenerated AP and poisons every
//   "no startAP" assertion downstream.
// - Counters are asserted as DELTAS snapshotted after setup — begin() and
//   pre-begin enableAP() legitimately touch the HAL before the scenario
//   starts.
// - Core::loop() is a no-op before Core::begin(); events emitted during
//   begin() are queued, not dispatched, so subscribers attach before begin()
//   and assert after one loop().

#include <unity.h>
#include <DomoticsCore/Core.h>
#include <DomoticsCore/Wifi.h>
#include <DomoticsCore/WifiEvents.h>

#include <vector>

using namespace DomoticsCore;
using namespace DomoticsCore::Components;

using HAL::WiFiHAL::Mode;

static Core* testCore = nullptr;
static WifiComponent* wifiPtr = nullptr;

// Event capture — sequences, not just last values: F3 must see AP disabled by
// the arming loop and re-enabled by the success loop, in that order.
static std::vector<bool> staEvents;
static std::vector<bool> apEvents;
static std::vector<String> readyPayloads;

// Config-save capture (STA fallback timeout and the ultra-low-heap guard both
// persist autoConnect=false to break boot loops).
static bool configSaved = false;
static WifiConfig savedConfig;

void setUp(void) {
    // Before any construction — see the fixture invariants above.
    HAL::Platform::setMillisForTest(0);
    HAL::Platform::resetFreeHeapForTest();
    HAL::Platform::resetRestartCountForTest();
    HAL::WiFiImpl::resetWifiStateForTest();
    HAL::WiFiImpl::setConnectedForTest(false);

    staEvents.clear();
    apEvents.clear();
    readyPayloads.clear();
    configSaved = false;
    savedConfig = WifiConfig();
}

void tearDown(void) {
    if (testCore) {
        testCore->shutdown();
        delete testCore;
        testCore = nullptr;
    }
    wifiPtr = nullptr;
    HAL::WiFiImpl::resetWifiStateForTest();
    HAL::WiFiImpl::resetScanForTest();
    HAL::WiFiImpl::setConnectedForTest(false);
    HAL::Platform::resetMillisForTest();
    HAL::Platform::resetFreeHeapForTest();
    HAL::Platform::resetRestartCountForTest();
}

static void subscribeAll() {
    testCore->getEventBus().subscribe(WifiEvents::EVENT_STA_CONNECTED, [](const void* p) {
        if (p) staEvents.push_back(*static_cast<const bool*>(p));
    });
    testCore->getEventBus().subscribe(WifiEvents::EVENT_AP_ENABLED, [](const void* p) {
        if (p) apEvents.push_back(*static_cast<const bool*>(p));
    });
    testCore->getEventBus().subscribe(WifiEvents::EVENT_NETWORK_READY, [](const void* p) {
        // Emitted through the sized overload, length()+1 — a NUL-terminated
        // char*, deep-copied by the bus (BUG-30's contract).
        if (p) readyPayloads.push_back(String(static_cast<const char*>(p)));
    });
}

// Core-backed STA fixture: subscribers attached, begin() run. Leaves one
// connect() call recorded and a connection in progress at t=0.
static void buildStaFixture() {
    testCore = new Core();
    subscribeAll();
    auto wifi = std::make_unique<WifiComponent>("Net", "pw");
    wifiPtr = wifi.get();
    testCore->addComponent(std::move(wifi));
    testCore->begin();
}

static void captureConfigSave(const WifiConfig& cfg) {
    configSaved = true;
    savedConfig = cfg;
}

// Arms the STA fallback timer for real (review finding 1: heap 20000 takes the
// direct AP+STA branch at Wifi.h:805 and never arms anything — every fallback
// scenario must enter through a heap in [2000, 3500)).
// On return: stopAP fired once, mode is Station, no startAP yet, t unchanged.
static void armFallbackAt3000() {
    WifiConfig cfg;
    cfg.ssid = "Net";
    cfg.password = "pw";
    cfg.autoConnect = true;
    cfg.enableAP = true;
    cfg.apSSID = "FallAP";
    cfg.apPassword = "appw";
    wifiPtr->setConfig(cfg);  // defers to loop() via pendingModeUpdate_

    HAL::Platform::setFreeHeapForTest(3000);
    const auto& st = HAL::WiFiImpl::stubWifiState();
    unsigned stopBefore = st.stopAPCalls;
    unsigned startBefore = st.startAPCalls;
    testCore->loop();

    // The arming discriminator: this branch tears the AP down to free heap for
    // the STA attempt. Without it, F2/F3/F4 would pass through other paths.
    TEST_ASSERT_EQUAL_UINT(stopBefore + 1, st.stopAPCalls);
    TEST_ASSERT_EQUAL_UINT(startBefore, st.startAPCalls);
    TEST_ASSERT_EQUAL_INT((int)Mode::Station, (int)HAL::WiFiHAL::getMode());
}

