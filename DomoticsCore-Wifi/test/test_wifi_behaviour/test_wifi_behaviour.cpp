void test_begin_empty_ssid_starts_autogenerated_open_ap(void) {  // A1
    testCore = new Core();
    subscribeAll();
    auto wifi = std::make_unique<WifiComponent>("", "");
    wifiPtr = wifi.get();
    testCore->addComponent(std::move(wifi));
    testCore->begin();
    const auto& st = HAL::WiFiImpl::stubWifiState();

    TEST_ASSERT_EQUAL_UINT(1, st.startAPCalls);
    // Stub MAC 00:00:00:00:00:00 → colons stripped → substring(6) → "000000".
    TEST_ASSERT_EQUAL_STRING("DomoticsCore-000000", st.apSSID.c_str());
    TEST_ASSERT_TRUE(st.lastAPPasswordWasNull);  // open network
    TEST_ASSERT_EQUAL_INT((int)Mode::AccessPoint, (int)HAL::WiFiHAL::getMode());
    TEST_ASSERT_TRUE(wifiPtr->isAPEnabled());
    TEST_ASSERT_FALSE(wifiPtr->isWifiEnabled());

    testCore->loop();  // begin() queues, the first loop dispatches
    TEST_ASSERT_EQUAL_INT(1, (int)apEvents.size());
    TEST_ASSERT_TRUE(apEvents[0]);
    TEST_ASSERT_EQUAL_INT(1, (int)readyPayloads.size());
    TEST_ASSERT_EQUAL_STRING("0.0.0.0", readyPayloads[0].c_str());
}

void test_begin_empty_ssid_preconfigured_ap(void) {  // A2
    testCore = new Core();
    subscribeAll();
    auto wifi = std::make_unique<WifiComponent>("", "");
    wifiPtr = wifi.get();
    // Pre-begin, like System does with its deviceName-based SSID. This call
    // itself runs updateWifiMode() and starts the AP once already — begin()'s
    // preconfigured branch is the second startAP. Deltas, not totals.
    wifiPtr->enableAP("MyAP", "appw", true);
    const auto& st = HAL::WiFiImpl::stubWifiState();
    unsigned afterEnable = st.startAPCalls;

    testCore->addComponent(std::move(wifi));
    testCore->begin();

    TEST_ASSERT_EQUAL_UINT(afterEnable + 1, st.startAPCalls);
    TEST_ASSERT_EQUAL_STRING("MyAP", st.apSSID.c_str());
    TEST_ASSERT_FALSE(st.lastAPPasswordWasNull);
    TEST_ASSERT_EQUAL_INT((int)Mode::AccessPoint, (int)HAL::WiFiHAL::getMode());
    TEST_ASSERT_EQUAL_INT((int)ComponentStatus::Success, (int)wifiPtr->getLastStatus());
    // NOT asserted: isWifiEnabled() false — the pre-begin enableAP already
    // forced it through the stale-config guard; asserting it here would pin
    // the wrong line (review finding 7).
}

void test_ap_only_update_skips_restart_when_already_running(void) {  // A3
    HAL::WiFiImpl::setStartAPResultForTest(true);  // the skip check reads getAPSSID(), which needs a live AP
    testCore = new Core();
    subscribeAll();
    auto wifi = std::make_unique<WifiComponent>("", "");
    wifiPtr = wifi.get();
    wifiPtr->enableAP("MyAP", "appw", true);
    testCore->addComponent(std::move(wifi));
    testCore->begin();
    testCore->loop();
    const auto& st = HAL::WiFiImpl::stubWifiState();

    // Same AP again through the WebUI-save path (setConfig → deferred update).
    unsigned startBefore = st.startAPCalls;
    unsigned disconnectBefore = st.disconnectCalls;
    WifiConfig cfg;
    cfg.ssid = "";
    cfg.autoConnect = false;
    cfg.enableAP = true;
    cfg.apSSID = "MyAP";
    cfg.apPassword = "appw";
    wifiPtr->setConfig(cfg);
    testCore->loop();

    // The AP is already up with that SSID: no restart, no disconnect — the
    // brief AP dropout this branch prevents is the point.
    TEST_ASSERT_EQUAL_UINT(startBefore, st.startAPCalls);
    TEST_ASSERT_EQUAL_UINT(disconnectBefore, st.disconnectCalls);
    TEST_ASSERT_TRUE(st.apActive);
}

void test_stale_config_wifi_enabled_without_ssid_is_disabled(void) {  // A4
    WifiComponent wifi;  // standalone
    WifiConfig cfg;
    cfg.ssid = "";
    cfg.autoConnect = true;  // the stale half-config a crash can leave behind
    cfg.enableAP = false;
    wifi.setConfig(cfg);
    wifi.loop();  // deferred updateWifiMode runs here

    TEST_ASSERT_FALSE(wifi.isWifiEnabled());
    // The guard's other half: shouldConnect = false, observable through
    // getConfig().autoConnect. (A connectCalls assert stood here first and was
    // vacuous — no rewrite of the guard can make updateWifiMode() connect.)
    TEST_ASSERT_FALSE(wifi.getConfig().autoConnect);
}

